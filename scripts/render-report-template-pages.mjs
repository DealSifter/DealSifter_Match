import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createCanvas, DOMMatrix, ImageData, Path2D } from '@napi-rs/canvas';
import { reportPreviewRendererFingerprint } from './report-preview-fingerprint.mjs';

Object.assign(globalThis, { DOMMatrix, ImageData, Path2D });
const { getDocument } = await import('pdfjs-dist/legacy/build/pdf.mjs');
const root = new URL('../', import.meta.url);
const output = new URL('qa/report-template/', root);
const previews = new URL('src/assets/maxxis/report-previews/', root);
const products = [['PROPERTY_RELEASE','property-release'],['MAXXIS_ANALYSIS','maxxis-analysis'],['DEAL_INTELLIGENCE','deal-intelligence']];
const manifest = { rendererFingerprint:await reportPreviewRendererFingerprint(root), reports:{} };
const imports=[], groups=[];
await Promise.all([mkdir(output,{recursive:true}),mkdir(previews,{recursive:true})]);
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
async function writeGenerated(file, bytes) {
  for (let attempt = 0; ; attempt += 1) {
    try { await writeFile(file, bytes); return; }
    catch (error) {
      if (attempt >= 5 || !['EBUSY', 'EPERM', 'EACCES', 'UNKNOWN'].includes(error.code)) throw error;
      await new Promise(resolve => setTimeout(resolve, 200 * (attempt + 1)));
    }
  }
}
for (const [type, product] of products) {
  const bytes = new Uint8Array(await readFile(new URL(`${product}.pdf`, output)));
  const loadingTask = getDocument({ data: bytes.slice(), useSystemFonts: true });
  const pdf = await loadingTask.promise;
  const pages=[];
  try {
    for (let number = 1; number <= pdf.numPages; number += 1) {
      const page = await pdf.getPage(number);
      const viewport = page.getViewport({scale:2});
      const canvas = createCanvas(Math.ceil(viewport.width),Math.ceil(viewport.height));
      const context = canvas.getContext('2d');context.fillStyle='#ffffff';context.fillRect(0,0,canvas.width,canvas.height);
      await page.render({canvasContext:context,viewport,canvas}).promise;
      const png=await canvas.encode('png'),file=`${product}-page-${number}.png`,id=`${type}Page${number}`;
      await Promise.all([writeGenerated(new URL(file,output),png),writeGenerated(new URL(file,previews),png)]);
      imports.push(`import ${id} from './${file}';`);
      pages.push({file,sha256:sha256(png),width:canvas.width,height:canvas.height});
      process.stdout.write(`${file}: ${canvas.width}x${canvas.height}\n`);
    }
    manifest.reports[type]={product,pageCount:pdf.numPages,pdfSha256:sha256(bytes),pages};
    groups.push(`  ${type}:Object.freeze([${pages.map((_,i)=>`${type}Page${i+1}`).join(',')}]),`);
    // Remove only obsolete pages for this exact report from the two generated directories.
    for(const directory of [output,previews])for(const name of await readdir(directory)){
      const match=name.match(new RegExp(`^${product}-page-(\\d+)\\.png$`));
      if(match&&Number(match[1])>pdf.numPages)await unlink(new URL(name,directory));
    }
  } finally { await loadingTask.destroy(); }
}
await writeFile(new URL('pages.js',previews),`// Generated by npm run qa:reports:generate from the production PDF renderer.\n${imports.join('\n')}\n\nexport const REPORT_PREVIEW_PAGES = Object.freeze({\n${groups.join('\n')}\n});\n`);
await writeFile(new URL('manifest.json',previews),JSON.stringify(manifest,null,2)+'\n');
